import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const dist = join(root, "dist");

// Keep editable HTML in app/. The root HTML is a built page that also works
// when GitHub Pages is configured to publish main:/ without running Vite.
const html = (await readFile(join(dist, "app/index.html"), "utf8"))
  .replace(/((?:src|href)=["'])(?:\.\.\/)+/g, "$1./");
await writeFile(join(dist, "index.html"), html);
await rm(join(dist, "app"), { recursive: true });
await writeFile(join(dist, ".nojekyll"), "");

async function files(directory, prefix = "") {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = prefix + entry.name;
    if (entry.isDirectory()) result.push(...await files(join(directory, entry.name), path + "/"));
    else if (entry.isFile()) result.push(path);
  }
  return result;
}

const generated = await files(dist);
let previous = [];
try { previous = JSON.parse(await readFile(join(root, ".pages-files.json"), "utf8")); }
catch (error) { if (error.code !== "ENOENT") throw error; }

// Remove only obsolete files recorded as generated by this script.
for (const path of previous) {
  if (!generated.includes(path) && /^(assets|onnx)\/[\w.-]+$/.test(path)) {
    await rm(join(root, path), { force: true });
  }
}
for (const path of generated) {
  const destination = join(root, path);
  await mkdir(join(destination, ".."), { recursive: true });
  await cp(join(dist, path), destination);
}
await writeFile(join(root, ".pages-files.json"), JSON.stringify(generated.sort(), null, 2) + "\n");
console.log("Prepared dist/ and the branch-published static site at the repository root.");
